const ENGLISHISH =
  /\b(the|and|with|that|which|this|from|have|has|been|were|would|could|should|about|into|their|there|when|what|while|after|before|because|is|are|was|of|for|our|his|her|they|them|you|your|we|not|but|or|as|by|on|in|to|it|its|be|been|being|do|does|did|will|can|may|might|than|then|also|only|just|still|very|more|most|some|any|all|such|these|those|here|where|who|how|why|if)\b/gi;

export function toFrenchChessProse(english) {
  if (!english || !String(english).trim()) return "";
  let text = String(english);
  for (const [pattern, replacement] of PHRASES) {
    text = text.replace(pattern, replacement);
  }
  text = text
    .replace(/\bdes Noirs (Cavalier|Fou|Roi|Pion)\b/g, "le $1 des Noirs")
    .replace(/\bdes Blancs (Cavalier|Fou|Roi|Pion)\b/g, "le $1 des Blancs")
    .replace(/\bdes Noirs (Tour|Dame)\b/g, "la $1 des Noirs")
    .replace(/\bdes Blancs (Tour|Dame)\b/g, "la $1 des Blancs")
    .replace(/\bde la Tour’s\b/g, "de la Tour")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([.,;:!?])/g, "$1")
    .trim();
  text = text.replace(/(^|[.!?]\s+)([a-zàâäéèêëïîôùûüç])/g, (_, a, b) => a + b.toUpperCase());
  return text;
}

/** Prefer FR only when enough English glue words were removed; else keep EN. */
export function frenchOrOriginal(english) {
  const fr = toFrenchChessProse(english);
  if (!fr) return "";
  const remaining = fr.match(ENGLISHISH)?.length ?? 0;
  const words = fr.split(/\s+/).filter(Boolean).length;
  if (words > 8 && remaining / words > 0.12) return english;
  return fr;
}
